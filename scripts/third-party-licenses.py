#!/usr/bin/env python3
"""Writes THIRD_PARTY_LICENSES.txt: the notices of the third-party software
the Controller apps and the WebUI server ship.

    scripts/third-party-licenses.py          regenerate the file
    scripts/third-party-licenses.py --check  fail if it is out of date (CI)

Sources:
  - Rust crates: cargo-about (`cargo install cargo-about --locked --features cli`) over this
    crate and the JNI crate (compose/rust, which pulls in Core for Android),
    all features; accepted licenses in about.toml.  Needs Core checked out
    next to this repository, as for building.
  - Maven modules (Kotlin, Compose, AndroidX): the `thirdPartyModules` Gradle
    task (compose/build.gradle.kts), which reads the licenses from the POMs
    of what the desktop, Android and web apps ship.
  - npm packages bundled into the web front end: the names in
    compose/kotlin-js-store/wasm/yarn.lock, each with its license text in
    licenses/npm/ (added by hand when a new package appears).
  - Fonts and icons: licenses/fonts/ and the table below.
"""

import json
import re
import subprocess
import sys
import tempfile
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COMPOSE = ROOT / "compose"
OUT = COMPOSE / "shared/src/commonMain/composeResources/files/THIRD_PARTY_LICENSES.txt"

# MSST-Net's own crates (Controller, Core), covered by LICENSE.
OWN_CRATE = re.compile(r"^msst[-_]")

# Bundled files that are not packages: (name, license id, text file or None
# for a license whose text comes from the packages above).
ASSETS = [
    ("寒蝉全圆体 ChillRound (UI font)", "OFL-1.1", ROOT / "licenses/fonts/ChillRound-OFL.txt"),
    ("JetBrains Mono (monospace font)", "OFL-1.1", ROOT / "licenses/fonts/JetBrainsMono-OFL.txt"),
    ("Material Design Icons, Pictogrammers (icon paths in MdiIcons.kt)", "Apache-2.0", None),
]

HEADER = """\
MSST-Net Controller — third-party software notices
==================================================

MSST-Net Controller is released under the MIT License (LICENSE in the
source repository).  MSST-Net's own code — the Controller and the
MSST-Net Core crates (msst-*) built into the Android app — is covered by
that license.  The Controller apps and the WebUI server also contain the
third-party software listed below; its licenses follow the list.

  - Rust crates: the WebUI server (msst-net-webui) and the native library
    of the desktop and Android apps.
  - Maven modules: the desktop, Android and web apps.
  - npm packages, fonts, icons: the user interface of every app.

The desktop packages also contain a Java runtime (OpenJDK, GPL-2.0 with
the Classpath Exception); its notices are in the runtime's legal directory
inside the package.

Generated by scripts/third-party-licenses.py; do not edit by hand.
"""


def run(cmd, cwd):
    subprocess.run(cmd, cwd=cwd, check=True)


def cargo_about(manifest_dir, tmp):
    out = Path(tmp) / f"{manifest_dir.name}.json"
    run(["cargo", "about", "generate", "--format", "json", "--all-features",
         "-c", str(ROOT / "about.toml"), "-o", str(out)], manifest_dir)
    return json.loads(out.read_text())


def normalize(text):
    lines = [l.rstrip() for l in text.replace("\r\n", "\n").strip("\n").split("\n")]
    return "\n".join(lines)


def maven_modules():
    run(["./gradlew", "-q", "thirdPartyModules"], COMPOSE)
    modules = []
    for line in (COMPOSE / "build/third-party-modules.tsv").read_text().splitlines():
        coord, *licenses = line.split("\t")
        ids = set()
        for lic in licenses:
            name, _, url = lic.partition("|")
            if re.search(r"apache", name, re.I) and re.search(r"2\.0", name + url):
                ids.add("Apache-2.0")
            else:
                sys.exit(f"{coord}: license {lic!r} is not known to this script; add it")
        if not ids:
            sys.exit(f"{coord}: its POM declares no license")
        group, module, version = coord.split(":")
        modules.append((f"{group}:{module} {version}", ids))
    return modules


def npm_packages():
    lock = (COMPOSE / "kotlin-js-store/wasm/yarn.lock").read_text()
    packages = []
    for name, version in re.findall(r'^"?(@?[^@\s"]+)@[^\n]*:\n\s+version "([^"]+)"', lock, re.M):
        text = ROOT / "licenses/npm" / (name.lstrip("@").replace("/", "-") + ".LICENSE")
        if not text.exists():
            sys.exit(f"npm package {name} has no license text in licenses/npm/ ({text.name})")
        first = text.read_text().splitlines()[0]
        if "BSD" not in first:
            sys.exit(f"{text.name}: only BSD-licensed npm packages are known to this script; add {first!r}")
        packages.append((f"{name} {version}", "BSD-3-Clause", text))
    return packages


def main():
    check = "--check" in sys.argv[1:]

    # License text -> what uses it.
    groups = {}
    users = defaultdict(set)
    crate_licenses = defaultdict(set)

    def add(lic_id, name, text, user):
        key = normalize(text)
        groups.setdefault(key, (lic_id, name))
        users[key].add(user)

    with tempfile.TemporaryDirectory() as tmp:
        for manifest_dir in (ROOT, COMPOSE / "rust"):
            for lic in cargo_about(manifest_dir, tmp)["licenses"]:
                for use in lic["used_by"]:
                    crate = use["crate"]
                    if OWN_CRATE.match(crate["name"]):
                        continue
                    user = f'{crate["name"]} {crate["version"]}'
                    crate_licenses[user].add(lic["id"])
                    add(lic["id"], lic["name"], lic["text"], user)

    # Maven modules and the icons are Apache-2.0; they use the most common
    # Apache-2.0 text from the crates (the plain license).
    apache = max((k for k, (i, _) in groups.items() if i == "Apache-2.0"),
                 key=lambda k: (len(users[k]), k))
    modules = maven_modules()
    for user, _ in modules:
        users[apache].add(user)

    npm = npm_packages()
    for user, lic, text in npm:
        add(lic, 'BSD 3-Clause "New" or "Revised" License', text.read_text(), user)

    for name, lic, text in ASSETS:
        if text is None:
            users[apache].add(name)
        else:
            add(lic, "SIL Open Font License 1.1", text.read_text(), name)

    out = [HEADER, "", "Components", "----------", "", "Rust crates:"]
    out += [f"  {c}  ({' AND '.join(sorted(ids))})" for c, ids in sorted(crate_licenses.items())]
    out += ["", "Maven modules:"]
    out += [f"  {m}  ({' AND '.join(sorted(ids))})" for m, ids in sorted(modules)]
    out += ["", "npm packages:"]
    out += [f"  {p}  ({lic})" for p, lic, _ in sorted(npm)]
    out += ["", "Fonts and icons:"]
    out += [f"  {name}  ({lic})" for name, lic, _ in ASSETS]
    out += ["", "", "License texts", "-------------"]

    order = sorted(groups, key=lambda k: (groups[k][0], -len(users[k]), sorted(users[k])))
    for n, key in enumerate(order, 1):
        lic_id, name = groups[key]
        out += ["", "=" * 72, f"[{n}] {name} ({lic_id})", ""]
        out += ["Used by: " + ", ".join(sorted(users[key])), "", key]
    text = "\n".join(out) + "\n"

    if check:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT.relative_to(ROOT)} is out of date: run scripts/third-party-licenses.py")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.encode())} bytes, {len(order)} license texts)")


if __name__ == "__main__":
    main()
